        <div class="prose js-reveal">
          <h2 id="bodies-title">Written for the body you have today</h2>
          <p>Arm length, leg length, hip shape and shoulder range vary enormously between people, and none of that variation is a flaw to be corrected. A posture that requires a block under one person's hand requires nothing under another's, and the two are doing the same posture.</p>
          <p>So every pose entry on Stillpoint carries at least two accessible alternatives, and they are presented with the same weight as the standard shape:</p>
          <ul>
            <li><b>Chair.</b> Standing and seated postures adapted for a stable chair, for anyone who does not get up and down from the floor easily or who is practicing at a desk.</li>
            <li><b>Wall.</b> Balances and inversions with a wall behind or beside you, which removes the fear of falling and lets you pay attention to something else.</li>
            <li><b>Block.</b> Raising the floor to meet your hand, so the spine can stay long instead of rounding to reach.</li>
            <li><b>Strap.</b> Lengthening your reach so a bind or a fold does not depend on hamstring or shoulder range you do not currently have.</li>
            <li><b>Bolster and blanket.</b> Filling the space under a supported shape so that muscles can genuinely stop working.</li>
          </ul>
          <p>If you own none of these, the <a href="props-and-modifications.html">props and modifications guide</a> lists a household substitute for each one. A stack of books is a block. A bathrobe belt is a strap. A firm sofa cushion under a folded blanket is a bolster.</p>
          <p><a class="linkbtn" href="props-and-modifications.html">Read the props guide</a></p>
