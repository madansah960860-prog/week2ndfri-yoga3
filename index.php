          <h2 id="note-title">What Stillpoint is, and what it is not</h2>
          <p class="dropcap">Most yoga instruction assumes you can already see what the teacher is doing. Stillpoint assumes the opposite. Every entry is written to be read first and moved to second, so that a posture makes sense in your head before you ask your body to find it. We describe which joints move, which tissues lengthen, where the weight sits and what the breath is doing. We do not describe what a posture is supposed to fix, because that is not something a reference site can honestly claim.</p>
          <p>The library is organized the way a reference book is organized. Poses carry both their English and Sanskrit names, a difficulty reading, numbered entry steps, alignment cues, a suggested hold, the mistakes that most often show up, and at least two prop-supported alternatives. Sequences carry a total running time, a props list, and a pose-by-pose order with hold times you can actually follow with a timer.</p>
          <p>Nothing here is a substitute for a qualified teacher in a room with you, and nothing here is medical advice. Yoga is a physical activity. If you are pregnant, recently injured, recovering from surgery or managing any health condition, speak with a qualified healthcare professional before you begin, and read our <a href="health-safety-disclaimer.html">health and safety disclaimer</a> before your first practice.</p>
